"""
Pydantic models for OAuth Launchpad guides.

These models define the shape of every OAuth setup guide, whether it was
seeded by hand (GitHub, Slack, Google) or generated by the Tavily/TarqaAI
research pipeline. Keeping them in one small file makes it easy to see
the full data contract at a glance.
"""

import ipaddress
from datetime import datetime
from enum import Enum
from urllib.parse import urlparse

from pydantic import BaseModel, Field, field_validator


# --- Enums -------------------------------------------------------------
# Using enums (instead of raw strings) means invalid values are rejected
# automatically by Pydantic, and the frontend always receives one of a
# known, fixed set of values.

class SetupComplexity(str, Enum):
    low = "low"
    medium = "medium"
    high = "high"


class ApprovalStatus(str, Enum):
    """Whether the provider requires reviewing/approving the OAuth app
    before real users can connect through it."""

    required = "required"
    not_required = "not_required"
    unknown = "unknown"


class SetupPath(str, Enum):
    """Whether relying on a managed OAuth app (an auth aggregator that
    already has an approved app with this provider) looks sufficient, or
    whether registering your own ("custom") OAuth app is the better path.

    This is a product recommendation, not a scraped fact: it weighs how
    much friction custom registration has (self-serve vs. requiring
    provider review) against the branding/control you give up by relying
    on someone else's app. "unknown" is used whenever the evidence isn't
    strong enough to recommend one path over the other.
    """

    managed = "managed"
    custom = "custom"
    unknown = "unknown"


class ResponsibleParty(str, Enum):
    agent = "agent"
    developer = "developer"
    provider = "provider"


class VerificationStatus(str, Enum):
    verified = "verified"
    unverified = "unverified"
    conflicting = "conflicting"


# --- Shared URL safety check --------------------------------------------
# Any URL stored in a guide (a source link, a documentation page) must be
# a normal public http/https address. This blocks the obvious SSRF cases
# (localhost, private IPs, non-http schemes) at the data layer, so a bad
# URL can never even be saved. The research pipeline (research.py) does a
# second, stronger check with real DNS resolution before fetching a page,
# since a hostname can look public here but resolve to a private IP.

_BLOCKED_HOSTNAMES = {"localhost", "127.0.0.1", "0.0.0.0", "::1"}


def is_safe_public_url(url: str) -> bool:
    try:
        parsed = urlparse(url)
    except ValueError:
        return False

    if parsed.scheme not in ("http", "https"):
        return False

    hostname = parsed.hostname
    if not hostname:
        return False

    if hostname.lower() in _BLOCKED_HOSTNAMES:
        return False

    # If the hostname is itself a literal IP address, reject private,
    # loopback, and link-local ranges. (Hostnames that resolve to private
    # IPs via DNS are caught later, in research.py, before any fetch.)
    try:
        ip = ipaddress.ip_address(hostname)
        if ip.is_private or ip.is_loopback or ip.is_link_local or ip.is_reserved:
            return False
    except ValueError:
        pass  # Not an IP literal, so it's a normal hostname like "github.com"

    return True


class SourceEvidence(BaseModel):
    """A single piece of evidence backing a claim made in a guide."""

    title: str = Field(min_length=1)
    url: str
    supports_claim: str = Field(min_length=1)
    verification_status: VerificationStatus

    @field_validator("url")
    @classmethod
    def url_must_be_safe_public_address(cls, value: str) -> str:
        if not is_safe_public_url(value):
            raise ValueError("url must be a public http:// or https:// address")
        return value


class SetupStep(BaseModel):
    """One ordered instruction in the OAuth setup checklist."""

    id: str = Field(min_length=1)
    title: str = Field(min_length=1)
    instructions: str = Field(min_length=1)
    responsible_party: ResponsibleParty
    completed: bool = False


class RecoveryAction(BaseModel):
    """What to do about a specific blocker: the recovery step, the
    immediate next action, and who is responsible for it.

    This is a separate model (not just a string) because Screen 3 needs to
    show the fix, the next action, and whether the agent or a human handles
    it, as separate pieces of information.
    """

    for_blocker: str = Field(min_length=1)
    recovery_step: str = Field(min_length=1)
    next_action: str = Field(min_length=1)
    responsible_party: ResponsibleParty


class OAuthGuide(BaseModel):
    """A complete OAuth setup guide for one provider."""

    id: str = Field(min_length=1)
    provider_name: str = Field(min_length=1)
    canonical_domain: str = Field(min_length=1)
    category: str = ""
    summary: str = Field(min_length=1)

    recommended_setup_path: SetupPath
    setup_complexity: SetupComplexity
    estimated_hands_on_setup_hours: float = Field(ge=0)
    estimated_external_wait_days: float | None = Field(default=None, ge=0)

    # Never guessed: "unknown" is a first-class, honest answer.
    approval_status: ApprovalStatus

    prerequisites: list[str] = Field(default_factory=list)
    redirect_uri_requirements: str = ""
    required_scopes: list[str] = Field(default_factory=list)

    setup_steps: list[SetupStep] = Field(default_factory=list)

    # Common problems (plain descriptions) and, separately, the structured
    # guidance for recovering from them - kept as two lists instead of one
    # combined model so "what can go wrong" and "what to do about it" can
    # be rendered as their own sections.
    blockers: list[str] = Field(default_factory=list)
    recovery_actions: list[RecoveryAction] = Field(default_factory=list)

    sources: list[SourceEvidence] = Field(default_factory=list)
    unknowns: list[str] = Field(default_factory=list)

    last_researched_at: datetime

    @field_validator("canonical_domain")
    @classmethod
    def domain_must_look_like_a_domain(cls, value: str) -> str:
        # Accept "github.com" or "https://github.com", but reject anything
        # that isn't a plausible domain (no spaces, has at least one dot).
        candidate = value.strip()
        if candidate.startswith(("http://", "https://")):
            candidate = urlparse(candidate).hostname or ""
        if " " in candidate or "." not in candidate or candidate == "":
            raise ValueError("canonical_domain must be a plain domain, e.g. github.com")
        return value
